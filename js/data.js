/* ---------- Тақта бойынша жол (спираль) ----------
   Жасыл шарды айналатын 3 айналымды тікбұрышты спираль.
   Нүктелер салыстырмалы бірлікте (s = экран биіктігі).
   38 нүкте: 0=START, 1..36 = клетка, 37 = ФИНАЛ.
   Полилинияның бойымен тең аралықпен сэмплдеу → жол біркелкі.
*/
function buildSpiralUnits(){
  const R = [
    { ex: 0.450, ey: 0.360 },   // сыртқы айналым
    { ex: 0.335, ey: 0.260 },   // ортаңғы айналым
    { ex: 0.220, ey: 0.185 }    // ішкі айналым
  ];
  const segs = [];
  for (let r = 0; r < R.length; r++){
    const { ex, ey } = R[r];
    const TL = [-ex, -ey], TR = [ex, -ey], BR = [ex, ey], BL = [-ex, ey];
    segs.push([TL, TR], [TR, BR], [BR, BL], [BL, TL]);
    if (r < R.length - 1){
      segs.push([TL, [-R[r+1].ex, -R[r+1].ey]]);
    }
  }
  // соңғы аяқ: ішкі айналымның жоғарғы сол бұрышынан → жоғарғы ортаға (ФИНАЛ)
  segs.push([[-R[2].ex, -R[2].ey], [0, -R[2].ey]]);

  const lens = segs.map(([a, b]) => Math.hypot(b[0]-a[0], b[1]-a[1]));
  const total = lens.reduce((s, l) => s + l, 0);

  const N = 38;
  const pts = [];
  for (let i = 0; i < N; i++){
    const target = (i / (N - 1)) * total;
    let acc = 0, found = null;
    for (let s = 0; s < segs.length; s++){
      const l = lens[s];
      if (target <= acc + l || s === segs.length - 1){
        const t = l > 0 ? Math.min(1, (target - acc) / l) : 0;
        const [a, b] = segs[s];
        found = [a[0] + (b[0]-a[0]) * t, a[1] + (b[1]-a[1]) * t];
        break;
      }
      acc += l;
    }
    pts.push(found || segs[segs.length-1][1].slice());
  }

  // START (0) және ФИНАЛ (37) нақты орны:
  pts[0]  = [-0.452, -0.362];
  pts[37] = [0, -0.212];

  // Тығыз тұрған нүктелерді итеру (repulsion) — клеткалар қабаттаспауы үшін
  return relax(pts, 0.10, [0, 37]);
}

function relax(pts, minDist, fixed = []){
  const P = pts.map(p => p.slice());
  const isFixed = i => fixed.includes(i);
  for (let it = 0; it < 120; it++){
    let moved = false;
    for (let i = 0; i < P.length; i++){
      for (let j = i + 1; j < P.length; j++){
        const dx = P[j][0] - P[i][0], dy = P[j][1] - P[i][1];
        const d = Math.hypot(dx, dy);
        if (d > 1e-6 && d < minDist){
          const push = (minDist - d) / 2;
          const ux = dx / d, uy = dy / d;
          if (!isFixed(i)){ P[i][0] -= ux * push; P[i][1] -= uy * push; }
          if (!isFixed(j)){ P[j][0] += ux * push; P[j][1] += uy * push; }
          moved = true;
        }
      }
    }
    // тақта шекарасына қысу
    for (let i = 0; i < P.length; i++){
      P[i][0] = Math.max(-0.545, Math.min(0.545, P[i][0]));
      P[i][1] = Math.max(-0.415, Math.min(0.415, P[i][1]));
    }
    if (!moved) break;
  }
  return P;
}
